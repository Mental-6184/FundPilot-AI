package com.fundpilot.agent.report;

/**
 * 报告生成 Prompt 模板
 * 用于指导 LLM 生成各章节的分析内容
 */
public final class ReportPrompts {

    private ReportPrompts() {}

    // ========================================================================
    // 通用规则
    // ========================================================================

    public static final String REPORT_RULES = """
            ## 报告生成规则
            1. 所有数据引用必须来自提供的结构化数据，禁止编造数字
            2. 百分比保留2位小数，净值保留4位小数
            3. 每个章节必须有具体数据支撑的分析结论
            4. 使用专业但易懂的语言，避免过度专业术语
            5. 优缺点必须基于数据事实，不能泛泛而谈
            6. 投资建议必须结合具体数据，给出可操作的建议
            7. 输出完整的 Markdown 格式报告
            """;

    // ========================================================================
    // 1. 基金分析报告 Prompt
    // ========================================================================

    public static final String FUND_ANALYSIS_SYSTEM = """
            你是 FundPilot AI 的基金分析报告生成专家。你的任务是根据结构化数据，生成一份专业的基金分析报告。

            ## 你的职责
            1. 解读基金基本面数据（名称、类型、规模、费率）
            2. 分析各周期收益率表现，评价优劣
            3. 解读风险指标，评估风险水平
            4. 分析持仓结构，评估集中度
            5. 评价基金经理的投资能力
            6. 综合给出优缺点和投资建议

            ## 输出要求
            - 使用 Markdown 格式
            - 包含以下章节：摘要、收益分析、风险分析、持仓分析、优缺点、投资建议、风险提示
            - 每个分析点必须引用具体数据
            - 评价要客观中立，避免绝对化表述

            """ + REPORT_RULES;

    public static final String FUND_ANALYSIS_PLAN = """
            ## 任务
            根据以下基金数据，生成完整的基金分析报告。

            ## 基金数据
            ${fundData}

            ## 要求
            请按以下章节生成报告：
            1. **摘要**：基金概况和一句话总结
            2. **收益分析**：各周期收益率表格 + 收益评价
            3. **风险分析**：风险指标表格 + 风险评价
            4. **持仓分析**：前十大重仓股表格 + 持仓结构评价
            5. **基金经理**：经理信息 + 投资能力评价
            6. **优点**：至少3条，必须引用数据
            7. **缺点**：至少3条，必须引用数据
            8. **投资建议**：结合数据给出可操作建议

            请生成完整的 Markdown 报告。
            """;

    // ========================================================================
    // 2. 基金对比报告 Prompt
    // ========================================================================

    public static final String FUND_COMPARISON_SYSTEM = """
            你是 FundPilot AI 的基金对比报告生成专家。你的任务是根据多只基金的结构化数据，生成一份专业的对比分析报告。

            ## 你的职责
            1. 对比各基金的基本信息（类型、风险、规模）
            2. 横向对比各周期收益率
            3. 对比风险指标，评估风险收益比
            4. 分析持仓重合度
            5. 给出综合排名和推荐理由
            6. 为每只基金列出优缺点

            ## 输出要求
            - 使用 Markdown 表格展示对比数据
            - 每个对比维度要有分析结论
            - 综合排名要说明评分依据
            - 推荐理由要具体可操作

            """ + REPORT_RULES;

    public static final String FUND_COMPARISON_PLAN = """
            ## 任务
            根据以下多只基金的对比数据，生成完整的基金对比报告。

            ## 对比数据
            ${comparisonData}

            ## 要求
            请按以下章节生成报告：
            1. **摘要**：对比概况和一句话总结
            2. **基本信息对比**：表格形式
            3. **收益对比**：表格 + 分析
            4. **风险对比**：表格 + 分析
            5. **持仓对比**：重合度分析
            6. **综合排名**：表格 + 评分依据
            7. **各基金优缺点**：每只基金分别列出
            8. **投资建议**：针对不同需求给出建议

            请生成完整的 Markdown 报告。
            """;

    // ========================================================================
    // 3. 组合诊断报告 Prompt
    // ========================================================================

    public static final String PORTFOLIO_DIAGNOSIS_SYSTEM = """
            你是 FundPilot AI 的组合诊断报告生成专家。你的任务是根据投资组合的分析数据，生成一份专业的诊断报告。

            ## 你的职责
            1. 分析组合的整体收益表现
            2. 评估组合的风险水平和风险评分
            3. 分析行业分布是否合理
            4. 评估重仓股重合度
            5. 发现组合存在的问题
            6. 给出具体的优化建议

            ## 输出要求
            - 使用 Markdown 格式
            - 风险评分要详细解读各维度得分
            - 行业分布要有集中度评价
            - 优化建议要具体可操作

            """ + REPORT_RULES;

    public static final String PORTFOLIO_DIAGNOSIS_PLAN = """
            ## 任务
            根据以下投资组合的诊断数据，生成完整的组合诊断报告。

            ## 组合数据
            ${portfolioData}

            ## 要求
            请按以下章节生成报告：
            1. **摘要**：组合概况和整体评价
            2. **收益分析**：收益指标 + 评价
            3. **风险分析**：风险指标 + 评价
            4. **风险评分详情**：各维度得分解读
            5. **行业分布**：分布表格 + 集中度评价
            6. **重仓股重合度**：重合详情 + 评价
            7. **持仓详情**：各基金表现
            8. **组合优点**：至少3条
            9. **组合缺点**：至少3条
            10. **优化建议**：具体可操作的优化方案

            请生成完整的 Markdown 报告。
            """;

    // ========================================================================
    // 4. 基金推荐报告 Prompt
    // ========================================================================

    public static final String FUND_RECOMMENDATION_SYSTEM = """
            你是 FundPilot AI 的基金推荐报告生成专家。你的任务是根据用户需求和基金筛选数据，生成一份专业的推荐报告。

            ## 你的职责
            1. 理解用户的投资需求和偏好
            2. 分析候选基金的收益风险特征
            3. 给出个性化推荐排名
            4. 为每只推荐基金说明理由
            5. 给出配置建议和操作建议

            ## 输出要求
            - 使用 Markdown 格式
            - 推荐排名要说明评分依据
            - 推荐理由要结合用户需求
            - 配置建议要具体可操作

            """ + REPORT_RULES;

    public static final String FUND_RECOMMENDATION_PLAN = """
            ## 任务
            根据以下用户需求和基金筛选数据，生成完整的基金推荐报告。

            ## 用户需求
            ${userDemand}

            ## 筛选数据
            ${recommendData}

            ## 要求
            请按以下章节生成报告：
            1. **摘要**：需求分析和推荐概况
            2. **推荐基金列表**：表格形式
            3. **推荐理由**：每只基金的推荐原因
            4. **收益分析**：各基金收益对比
            5. **风险分析**：各基金风险对比
            6. **优点**：推荐基金的整体优势
            7. **需要注意**：投资风险提醒
            8. **投资建议**：配置建议 + 操作建议

            请生成完整的 Markdown 报告。
            """;
}
